      <h2>1. Теоретические основы ритмического сольфеджио</h2>
      <p>
        Музыка традиционно рассматривается как искусство, организованное в <strong>пространстве звуковых высот</strong> и <strong>во времени</strong>. Однако в педагогической практике, особенно в рамках консерваторской традиции, доминирует <strong>высотно-ориентированная модель</strong>: мелодия, лад, гармония, интонация — всё это предполагает, что музыкальный звук обязательно обладает определённой частотой, тоновой функцией и ладовым контекстом.
      </p>
      <p>
        Эта модель исключительно эффективна для вокалистов, струнников, клавишников — но она <strong>неполна</strong>. Существует целый класс музыкальных практик, в которых <strong>высота звука отсутствует или вторична</strong>, а главным носителем смысла выступает <strong>время</strong>:  
