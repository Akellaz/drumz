      <h3>Целостность предмета</h3>
      <p>
        Ритмическое сольфеджио охватывает <strong>весь спектр музыкально-мыслительных операций</strong>, связанных со временем:
      </p>
      <ul>
        <li><strong>Восприятие</strong> — распознавание ритмических структур на слух (диктанты);</li>
        <li><strong>Представление</strong> — удержание формы в уме без внешней опоры;</li>
        <li><strong>Воспроизведение</strong> — точная артикуляция в заданной структуре;</li>
        <li><strong>Анализ</strong> — распознавание метрической логики в реальных музыкальных произведениях;</li>
        <li><strong>Творчество</strong> — импровизация и композиция в рамках ритмических систем.</li>
      </ul>
      <p>
        Таким образом, ритмическое сольфеджио — это <strong>не тренировка реакции</strong>, а <strong>развитие музыкального интеллекта во временном измерении</strong>.
      </p>
