      <h3>II. Уровни (ранги)</h3>
      <p>2.1. Существует 6 уровней, каждый из которых присваивается по результатам верификации Советом Мастеров:</p>
      <ol>
        <li><strong>Новичок</strong> — базовое владение ритмом, метрономом, простыми рудиментами.</li>
        <li><strong>Ударник</strong> — свободное владение популярными стилями (рок, поп, фанк), динамикой, сопровождением.</li>
        <li><strong>Барабанщик</strong> — игра в ансамбле, импровизация в рамках жанра, понимание музыкальной формы.</li>
        <li><strong>Мастер-ритма</strong> — глубокое владение 2+ стилями, работа с нечётными и полиметрическими размерами.</li>
        <li><strong>Сессионщик</strong> — профессиональный уровень: студийная запись, чтение партитур, быстрая адаптация.</li>
        <li><strong>Хранитель Удара</strong> — ведущий исполнитель, наставник, создатель оригинального материала.</li>
      </ol>
      <p>2.2. Присвоение уровня подтверждается <strong>цифровым сертификатом</strong> с уникальным QR-кодом, указанием инструмента и даты.</p>
      <p>2.3. Повышение уровня возможно только последовательно. Пропуск уровней запрещён.</p>

      <h3>III. Профессии (специализации)</h3>
      <p>3.1. Профессия — это стилево-функциональная ветвь развития, определяющая уникальный путь участника.</p>
      <p>3.2. Выбор первой профессии возможен после успешного завершения Уровня 1.</p>
      <p>3.3. Основные профессии:</p>
      <ul>
        <li><strong>Грув-мастер</strong> (поп/фанк/R&B)</li>
        <li><strong>Джаз-ритмист</strong> (джаз/свинг/фьюжн)</li>
        <li><strong>Метал-страж</strong> (метал/хард-рок)</li>
        <li><strong>Латин-дух</strong> (сальса/мамбо/афро-куба)</li>
        <li><strong>Этно-следопыт</strong> (африканские, индийские, ближневосточные традиции)</li>
        <li><strong>Студийный техник</strong> (многожанровая запись)</li>
        <li><strong>Шоу-перкуссионер</strong> (сценическое мастерство)</li>
        <li><strong>Педагог-наставник</strong> (методика и обучение)</li>
      </ul>
      <p>3.4. Все профессии равнозначны. Стилевые профессии фокусируются на жанре, функциональные — на роли. Выбор не ограничивает инструмент: например, «Джаз-ритмист» может играть на дарбуке в джазовом контексте.</p>
      <p>3.5. На Уровне 4 участник может выбрать <strong>вторичную специализацию</strong>. Она не даёт отдельного титула, но открывает гибридные задания и бонусные навыки.</p>
      <p>3.6. Смена основной профессии возможна через <strong>Испытание Перерождения</strong> — специальный модуль, подтверждающий готовность к новому пути.</p>

